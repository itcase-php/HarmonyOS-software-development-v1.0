'use strict';
// Preview fallback is generated from the same resources used by the device.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = locale => JSON.parse(fs.readFileSync(path.join(root,
  `entry/src/main/resources/${locale}/element/string.json`), 'utf8')).string;
const zh = read('base');
const en = read('en_US');
const names = new Set(zh.map(item => item.name));
if (names.size !== zh.length || new Set(en.map(item => item.name)).size !== en.length ||
  zh.length !== en.length || en.some(item => !names.has(item.name))) {
  throw new Error('Language resource keys must be unique and identical');
}
const rows = zh.map(item => ({ name: item.name, zh: item.value,
  en: en.find(entry => entry.name === item.name).value }));
const content = `// Generated by tools/generate-language-catalog.cjs. Edit string.json resources.\n` +
  `export interface LanguageEntry { name: string; zh: string; en: string; }\n` +
  `export const languageCatalog: LanguageEntry[] = ${JSON.stringify(rows, null, 2)};\n`;
const target = path.join(root, 'entry/src/main/ets/generated/LanguageCatalog.ets');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== content) throw new Error('Language catalog is stale');
} else fs.writeFileSync(target, content);
