"""Install the locally built, pinned OHOS Office runtime into the main HAP inputs.
No device access. Missing/invalid runtime is a build error, not an available capability.
"""
from pathlib import Path
import argparse, hashlib, json, shutil, zipfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--stage', type=Path, default=root / 'tmp/offline-engines/office-stage-probe/entry')
args = parser.parse_args()
stage = args.stage.resolve()
archive = stage / 'src/main/resources/rawfile/office-resources.zip'
libraries = sorted((stage / 'libs/arm64-v8a').glob('*'))
if not archive.is_file() or not libraries:
    raise SystemExit('Build the pinned Office Stage runtime before packaging the main app.')
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
manifest = {'version': '26.2.6.2', 'sourceRevision': 'ad5cf9fd4989cacf0bca866ebefc0ec8926cb0b2',
            'abi': 'arm64-v8a', 'resourcesSha256': sha(archive), 'libraries': [], 'resources': []}
target_libs = root / 'entry/libs/arm64-v8a'
target_resources = root / 'entry/src/main/resources/rawfile/office'
target_libs.mkdir(parents=True, exist_ok=True)
target_resources.mkdir(parents=True, exist_ok=True)
for library in libraries:
    if not library.is_file():
        continue
    with library.open('rb') as stream:
        header = stream.read(20)
    if header[:6] != b'\x7fELF\x02\x01' or int.from_bytes(header[18:20], 'little') != 183:
        raise SystemExit(f'Not an ELF64/AArch64 library: {library.name}')
    manifest['libraries'].append({'name': library.name, 'sha256': sha(library), 'byteSize': library.stat().st_size})
    shutil.copyfile(library, target_libs / library.name)
if not (target_libs / 'libsofficeapp.so').is_file():
    raise SystemExit('LibreOfficeKit library missing')
with zipfile.ZipFile(archive) as package:
    seen = set()
    for entry in package.infolist():
        path = Path(entry.filename)
        if path.is_absolute() or '..' in path.parts or '\\' in entry.filename or entry.filename in seen:
            raise SystemExit('Unsafe or duplicate resource entry')
        seen.add(entry.filename)
        if not entry.is_dir():
            manifest['resources'].append({'name': entry.filename, 'sha256': hashlib.sha256(package.read(entry)).hexdigest(), 'byteSize': entry.file_size})
    for required in ['program/fundamentalrc', 'program/unorc', 'fonts/DejaVuSans.ttf', 'LICENSE', 'NOTICE']:
        if required not in seen:
            raise SystemExit(f'Offline resource missing: {required}')
shutil.copyfile(archive, target_resources / 'runtime.zip')
headers = stage / 'src/main/cpp/include/LibreOfficeKit'
shutil.copytree(headers, root / 'entry/src/main/cpp/include/LibreOfficeKit', dirs_exist_ok=True)
text = json.dumps(manifest, indent=2) + '\n'
manifest_path = root / 'shared/engines/office-bundle.json'
manifest_path.parent.mkdir(parents=True, exist_ok=True)
manifest_path.write_text(text, encoding='utf-8')
(target_resources / 'manifest.json').write_text(text, encoding='utf-8')
digest = hashlib.sha256(text.encode()).hexdigest()
(root / 'entry/src/main/cpp/generated/office_bundle.h').write_text(
    '#pragma once\nnamespace hdm { inline constexpr const char* kOfficeBundleHash = "' + digest + '"; }\n')
(root / 'entry/src/main/ets/generated/OfficeBundle.ets').write_text(
    '// Generated by tools/package-office-main.py; no network required at runtime.\n'
    'export const officeBundleHash: string = "' + digest + '";\n'
    'export const officeArchiveHash: string = "' + manifest['resourcesSha256'] + '";\n')
print(json.dumps({'libraries': len(manifest['libraries']), 'resourceFiles': len(manifest['resources']),
                  'archiveBytes': archive.stat().st_size, 'manifestSha256': digest}))
