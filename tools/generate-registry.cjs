'use strict';
// Shared JSON is the only authored format source. Outputs are generated, never hand-edited.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname,'..');
execFileSync(process.execPath,[path.join(root,'tests/check-design.cjs')],{stdio:'inherit'});
const source = path.join(root,'shared/format-registry');
const formatsBytes = fs.readFileSync(path.join(source,'formats.json'));
const matrixBytes = fs.readFileSync(path.join(source,'conversion-matrix.json'));
const formats = JSON.parse(formatsBytes);
const matrix = JSON.parse(matrixBytes);
const sha = data => crypto.createHash('sha256').update(data).digest('hex');
function write(relative, text) {
  const file = path.join(root,relative);
  fs.mkdirSync(path.dirname(file),{recursive:true});
  fs.writeFileSync(file,text);
}
const metadata = {schemaVersion:formats.schemaVersion,configVersion:formats.configVersion,
  formatsSha256:sha(formatsBytes),matrixSha256:sha(matrixBytes),blockedFormats:formats.blockedFormats,
  engineIds:formats.engineIds,optionsProfileIds:formats.optionsProfileIds,
  validationProfileIds:formats.validationProfileIds,migrationAliases:formats.migrationAliases,
  securityPolicy:formats.securityPolicy,defaultBudget:formats.resourceProfiles.default,
  formatsCount:formats.formats.length,routesCount:matrix.routes.length};
write('entry/src/main/ets/generated/RegistryData.ets',
  '// Generated by tools/generate-registry.cjs. Do not hand-code the catalogue.\n'+
  "import { RegistryMetadata, RegistryFormat, ConversionRouteDefinition } from '../models/RegistryTypes';\n\n"+
  `export const registryMetadata: RegistryMetadata = ${JSON.stringify(metadata,null,2)};\n\n`+
  '// Complete offline catalogue: previews and demo planning must retain every approved entry.\n'+
  'export const bundledFormats: RegistryFormat[] = [\n'+
  formats.formats.map(format=>'  '+JSON.stringify(format)).join(',\n')+'\n];\n\n'+
  'export const bundledRoutes: ConversionRouteDefinition[] = [\n'+
  matrix.routes.map(route=>'  '+JSON.stringify(route)).join(',\n')+'\n];\n');
write('entry/src/main/cpp/generated/registry_metadata.h',
  '#pragma once\n// Generated from shared/format-registry.\n#include <cstdint>\nnamespace hdm {\n'+
  `inline constexpr std::uint32_t kSchemaVersion = ${formats.schemaVersion};\n`+
  `inline constexpr const char* kConfigVersion = ${JSON.stringify(formats.configVersion)};\n`+
  `inline constexpr const char* kFormatsHash = ${JSON.stringify(metadata.formatsSha256)};\n`+
  `inline constexpr const char* kMatrixHash = ${JSON.stringify(metadata.matrixSha256)};\n}\n`);
for (const [name,bytes] of [['formats.json',formatsBytes],['conversion-matrix.json',matrixBytes]])
  write(`entry/src/main/resources/rawfile/format-registry/${name}`,bytes);
write('entry/src/main/resources/rawfile/format-registry/manifest.json',JSON.stringify(metadata,null,2)+'\n');
const creators = formats.engineIds.map(id => ({id,name:'Create'+id[0].toUpperCase()+id.slice(1)+'Converter'}));
for (const {id,name} of creators) {
  const file = `entry/src/main/cpp/engines/${id}/${id}_converter.cpp`;
  if (!fs.existsSync(path.join(root,file))) write(file,
    '#include "../../core/missing_converter.h"\nnamespace hdm {\n'+
    `std::unique_ptr<IConverter> ${name}() { return std::make_unique<MissingConverter>(${JSON.stringify(id)}); }\n}\n`);
}
write('entry/src/main/cpp/core/engine_registry.cpp',
  '// Generated factory table. Real adapters keep their engineId and factory signature.\n'+
  '#include "engine_registry.h"\nnamespace hdm {\n'+
  creators.map(x=>`std::unique_ptr<IConverter> ${x.name}();`).join('\n')+'\n'+
  'struct Registration { const char* id; std::unique_ptr<IConverter> (*create)(); };\n'+
  'const Registration registrations[] = {\n'+creators.map(x=>`    {${JSON.stringify(x.id)}, ${x.name}},`).join('\n')+'\n};\n'+
  'std::unique_ptr<IConverter> CreateConverter(const std::string& engineId) {\n'+
  '    for (const auto& entry : registrations) if (engineId == entry.id) return entry.create();\n'+
  '    return nullptr;\n}\n}\n');
write('entry/src/main/cpp/generated/engine_sources.cmake',
  '# Generated list; generator never overwrites an existing adapter implementation.\nset(HDM_ENGINE_SOURCES\n'+
  creators.map(x=>`    engines/${x.id}/${x.id}_converter.cpp`).join('\n')+'\n)\n');
const protocol = fs.readFileSync(path.join(root,'entry/src/main/ets/models/NativeProtocol.ets'),'utf8');
// TypeScript declarations may not import .ets in HarmonyOS. Generate the same model declarations
// inside the native type package and check exact equivalence in the migration verifier.
write('entry/src/main/cpp/types/libentry/Protocol.d.ts',
  '// Generated from models/NativeProtocol.ets. Do not edit independently.\n'+protocol);
const errors = [...protocol.match(/export type ErrorCode = ([\s\S]*?);/)[1].matchAll(/'([A-Z_]+)'/g)].map(x=>x[1]);
write('entry/src/main/ets/generated/ErrorCatalog.ets',
  "// Generated from the protocol.\nimport { ErrorCode } from '../models/NativeProtocol';\n"+
  `export const errorCodes: ErrorCode[] = ${JSON.stringify(errors,null,2)};\n`);
console.log(JSON.stringify({generatedFormats:formats.formats.length,generatedRoutes:matrix.routes.length,
  rawfileCopies:'byte-identical',formatsSha256:metadata.formatsSha256,matrixSha256:metadata.matrixSha256}));
